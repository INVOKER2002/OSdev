// Clear the framebuffer with color 0 (black)
void init_framebuffer() {
    for(uint32_t i = 0; i < VGA_WIDTH * VGA_HEIGHT; i++) {
        framebuffer[i] = 0;
    }
}

// Draw a single pixel at (x,y) with specified color
void put_pixel(uint16_t x, uint16_t y, uint8_t color) {
    if(x < VGA_WIDTH && y < VGA_HEIGHT) {
        framebuffer[y * VGA_WIDTH + x] = color;
    }
}

// Draw a filled rectangle at (x,y) with width w and height h
void draw_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint8_t color) {
    for(uint16_t j = 0; j < h; j++) {
        for(uint16_t i = 0; i < w; i++) {
            put_pixel(x + i, y + j, color);
        }
    }
}

// Draw a character at position (x,y) with specified color
void draw_char(uint16_t x, uint16_t y, char c, uint8_t color) {
    if (c < 0 || c > 127) {
        c = '?'; // Default to '?' for non-ASCII characters
    }
    
    const uint8_t* char_data = font8x8[(uint8_t)c];
    
    for(uint8_t j = 0; j < 8; j++) {
        for(uint8_t i = 0; i < 8; i++) {
            if(char_data[j] & (1 << i)) {
                put_pixel(x + i, y + j, color);
            }
        }
    }
}

// Draw text string at position (x,y) with specified color
void draw_text(uint16_t x, uint16_t y, const char* text, uint8_t color) {
    uint16_t cursor_x = x;
    uint16_t cursor_y = y;
    
    while(*text) {
        char c = *text++;
        
        // Handle newline
        if(c == '\n') {
            cursor_x = x;
            cursor_y += 9;
            continue;
        }
        
        // Draw the character
        draw_char(cursor_x, cursor_y, c, color);
        
        // Move cursor to next position
        cursor_x += 8;
        
        // Wrap text if it exceeds screen width
        if(cursor_x >= VGA_WIDTH - 8) {
            cursor_x = x;
            cursor_y += 9;
        }
    }
}

