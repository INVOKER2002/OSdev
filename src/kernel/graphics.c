// Draw a circle with center at (x, y) and specified radius
void draw_circle(uint16_t x, uint16_t y, uint16_t radius, uint8_t color) {
    int f = 1 - radius;
    int ddF_x = 0;
    int ddF_y = -2 * radius;
    int x1 = 0;
    int y1 = radius;
    
    put_pixel(x, y + radius, color);
    put_pixel(x, y - radius, color);
    put_pixel(x + radius, y, color);
    put_pixel(x - radius, y, color);
    
    while(x1 < y1) {
        if(f >= 0) {
            y1--;
            ddF_y += 2;
            f += ddF_y;
        }
        x1++;
        ddF_x += 2;
        f += ddF_x + 1;
        
        put_pixel(x + x1, y + y1, color);
        put_pixel(x - x1, y + y1, color);
        put_pixel(x + x1, y - y1, color);
        put_pixel(x - x1, y - y1, color);
        put_pixel(x + y1, y + x1, color);
        put_pixel(x - y1, y + x1, color);
        put_pixel(x + y1, y - x1, color);
        put_pixel(x - y1, y - x1, color);
    }
}

// Draw a filled circle
void draw_filled_circle(uint16_t x, uint16_t y, uint16_t radius, uint8_t color) {
    int16_t f = 1 - radius;
    int16_t ddF_x = 1;
    int16_t ddF_y = -2 * radius;
    int16_t x1 = 0;
    int16_t y1 = radius;
    
    for(int16_t i = y - radius; i <= y + radius; i++) {
        put_pixel(x, i, color);
    }
    
    while(x1 < y1) {
        if(f >= 0) {
            y1--;
            ddF_y += 2;
            f += ddF_y;
        }
        x1++;
        ddF_x += 2;
        f += ddF_x;
        
        for(int16_t i = y - y1; i <= y + y1; i++) {
            put_pixel(x + x1, i, color);
            put_pixel(x - x1, i, color);
        }
        
        for(int16_t i = y - x1; i <= y + x1; i++) {
            put_pixel(x + y1, i, color);
            put_pixel(x - y1, i, color);
        }
    }
}

// Draw a line from (x0,y0) to (x1,y1) using Bresenham's algorithm
void draw_line(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1, uint8_t color) {
    int16_t dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int16_t sx = (x0 < x1) ? 1 : -1;
    int16_t dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int16_t sy = (y0 < y1) ? 1 : -1;
    int16_t err = ((dx > dy) ? dx : -dy) / 2;
    int16_t e2;
    
    while(1) {
        put_pixel(x0, y0, color);
        
        if(x0 == x1 && y0 == y1) {
            break;
        }
        
        e2 = err;
        
        if(e2 > -dx) {
            err -= dy;
            x0 += sx;
        }
        
        if(e2 < dy) {
            err += dx;
            y0 += sy;
        }
    }
}

// Draw a simple progress bar
void draw_progress_bar(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint8_t progress, uint8_t border_color, uint8_t bg_color, uint8_t fill_color) {
    // Ensure progress is between 0 and 100
    if(progress > 100) {
        progress = 100;
    }
    
    // Draw background
    draw_rect(x, y, w, h, bg_color);
    
    // Draw border
    draw_border(x, y, w, h, border_color);
    
    // Calculate the width of the filled part
    uint16_t fill_width = (w - 2) * progress / 100;
    
    // Draw filled part
    if(fill_width > 0) {
        draw_rect(x + 1, y + 1, fill_width, h - 2, fill_color);
    }
}

