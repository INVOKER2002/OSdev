// Draw a border around a rectangle (simple window/button borders)
void draw_border(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint8_t color) {
    // Top border
    draw_rect(x, y, w, 1, color);
    // Bottom border
    draw_rect(x, y + h - 1, w, 1, color);
    // Left border
    draw_rect(x, y, 1, h, color);
    // Right border
    draw_rect(x + w - 1, y, 1, h, color);
}

// Draw a basic button with text
void draw_button(uint16_t x, uint16_t y, uint16_t w, uint16_t h, const char* text, uint8_t button_color, uint8_t text_color) {
    // Button background
    draw_rect(x, y, w, h, button_color);
    
    // Button border
    draw_border(x, y, w, h, text_color);
    
    // Center the text on the button
    uint16_t text_length = 0;
    const char* temp = text;
    while(*temp) {
        text_length++;
        temp++;
    }
    
    uint16_t text_x = x + (w - text_length * 8) / 2;
    uint16_t text_y = y + (h - 8) / 2;
    
    // Draw the text
    draw_text(text_x, text_y, text, text_color);
}

