// Set the VGA mode to 13h (320x200, 256 colors)
int set_graphics_mode(uint16_t width, uint16_t height, uint8_t depth) {
    if (width != 320 || height != 200 || depth != 256) {
        printf("Unsupported graphics mode: %dx%dx%d\n", width, height, depth);
        return 0;
    }

    printf("Setting graphics mode: %dx%dx%d\n", width, height, depth);

    // Set VGA Mode 13h (320x200, 256 colors)
    i686_outb(0x3C2, 0x63);
    i686_outb(0x3D4, 0x11);
    i686_outb(0x3D5, 0x0);
    
    i686_outb(0x3C4, 0x01);  // Sequencer: Clocking Mode Register
    i686_outb(0x3C5, 0x01);  // Turn off screen to avoid flicker
    
    // Set up various VGA registers for mode 13h
    i686_outb(0x3C4, 0x04);  // Sequencer: Memory Mode Register
    i686_outb(0x3C5, 0x06);  // Plane Write Enable: 0110
    
    i686_outb(0x3CE, 0x05);  // Graphics: Mode Register
    i686_outb(0x3CF, 0x40);  // Set 256-color mode
    
    i686_outb(0x3CE, 0x06);  // Graphics: Miscellaneous Register
    i686_outb(0x3CF, 0x05);  // Memory map: A0000-AFFFF
    
    i686_outb(0x3C4, 0x01);  // Sequencer: Clocking Mode Register
    i686_outb(0x3C5, 0x01);  // Turn screen back on
    
    i686_outb(0x3C4, 0x0F);  // Enable all planes
    i686_outb(0x3D4, 0x03);  // End Horizontal Blanking
    i686_outb(0x3D5, 0x82);
    
    i686_outb(0x3d4, 0x00);  // Horizontal Total
    i686_outb(0x3d5, 0x5f);
    i686_outb(0x3d4, 0x01);  // Horizontal Displayed
    i686_outb(0x3d5, 0x4f);
    i686_outb(0x3d4, 0x02);  // Start Horizontal Blanking
    i686_outb(0x3d5, 0x50);
    i686_outb(0x3d5, 0x50);
    i686_outb(0x3d4, 0x03);  // End Horizontal Blanking
    i686_outb(0x3d5, 0x82);
    i686_outb(0x3d4, 0x04);  // Start Horizontal Retrace
    i686_outb(0x3d5, 0x54);
    i686_outb(0x3d4, 0x05);  // End Horizontal Retrace
    i686_outb(0x3d5, 0x80);
    i686_outb(0x3d4, 0x06);  // Vertical Total
    i686_outb(0x3d5, 0xbf);
    i686_outb(0x3d4, 0x07);  // Overflow
    i686_outb(0x3d5, 0x1f);
    i686_outb(0x3d4, 0x08);  // Preset Row Scan
    i686_outb(0x3d5, 0x00);
    i686_outb(0x3d4, 0x09);  // Maximum Scan Line
    i686_outb(0x3d5, 0x41);
    i686_outb(0x3d4, 0x10);  // Vertical Start Retrace
    i686_outb(0x3d5, 0x9c);
    i686_outb(0x3d4, 0x11);  // Vertical End Retrace
    i686_outb(0x3d5, 0x8e);
    i686_outb(0x3d4, 0x12);  // Vertical Display End
    i686_outb(0x3d5, 0x8f);
    i686_outb(0x3d4, 0x13);  // Offset
    i686_outb(0x3d5, 0x28);
    i686_outb(0x3d4, 0x14);  // Underline Location
    i686_outb(0x3d5, 0x00);
    i686_outb(0x3d4, 0x15);  // Start Vertical Blanking
    i686_outb(0x3d5, 0x96);
    i686_outb(0x3d4, 0x16);  // End Vertical Blanking
    i686_outb(0x3d5, 0xb9);
    i686_outb(0x3d4, 0x17);  // CRTC Mode Control
    i686_outb(0x3d5, 0xa3);
    
    printf("Graphics mode set successfully.\n");
    return 1;
}

